'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
module.exports=async function({main,store,ai,safeStorage,directory}){
  const evaluate=code=>main.webContents.executeJavaScript(code);
  await evaluate('document.fonts.ready');
  const initial=await evaluate('window.companion.state()');
  const key='synthetic-deepseek-key-for-ui-test';
  const settings={...initial.settings,chatProvider:'deepseek',deepseekChatModel:'deepseek-flash',deepseekKey:key,wakeEnabled:false};
  ai.history=[{role:'user',content:'old provider context'}];
  await evaluate('window.companion.saveSettings('+JSON.stringify(settings)+')');
  const saved=await evaluate('window.companion.state()');
  assert.equal(saved.settings.chatProvider,'deepseek');assert.equal(saved.hasDeepSeekKey,true);
  assert.equal(saved.settings.transcriptionProvider,'local');assert.equal(saved.settings.localOnly,true);
  assert.ok(!JSON.stringify(saved).includes(key));assert.equal(saved.encryptedDeepSeekKey,undefined);
  assert.equal(ai.history.length,0);
  const disk=JSON.parse(fs.readFileSync(store.file,'utf8'));
  assert.ok(!JSON.stringify(disk).includes(key));
  assert.equal((await safeStorage.decryptStringAsync(Buffer.from(disk.encryptedDeepSeekKey,'base64'))).result,key);
  await evaluate("go('settings');loadState()");
  assert.equal(await evaluate("document.getElementById('chatProvider').value"),'deepseek');
  assert.equal(await evaluate("document.getElementById('deepseekSettings').hidden"),false);
  assert.equal(await evaluate("document.getElementById('deepseekKey').value"),'');
  assert.match(await evaluate("document.getElementById('deepseekKeyStatus').textContent"),/saved securely/);
  assert.equal(await evaluate("typeof window.companion.testDeepSeek"),'function');
  assert.equal(await evaluate("document.getElementById('setupBanner').hidden"),true);
  const changed={...settings,deepseekKey:'',deepseekChatModel:'unsupported-model'};
  await assert.rejects(evaluate('window.companion.saveSettings('+JSON.stringify(changed)+')'),/Choose DeepSeek Flash/);
  assert.equal(store.data.settings.deepseekChatModel,settings.deepseekChatModel);
  ai.busy=true;
  try{await assert.rejects(evaluate('window.companion.saveSettings('+JSON.stringify({...settings,deepseekKey:''})+')'),/End the current conversation/);}finally{ai.busy=false;}
  await evaluate('window.companion.saveSettings('+JSON.stringify({...settings,deepseekKey:'',chatProvider:'local'})+')');
  assert.equal(store.data.settings.chatProvider,'local');
  assert.equal((await evaluate('window.companion.state()')).hasDeepSeekKey,true);
  await evaluate('window.companion.saveSettings('+JSON.stringify({...settings,deepseekKey:''})+')');
  await evaluate("go('settings');loadState()");
  assert.equal(await evaluate("document.querySelector('.page.active').id"),'settings');
  await evaluate("document.getElementById('deepseekSettings').scrollIntoView({block:'center'})");
  await evaluate('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');
  await new Promise(resolve=>setTimeout(resolve,250));
  fs.writeFileSync(path.join(directory,'deepseek-provider-settings.png'),(await main.webContents.capturePage()).toPNG());
  await evaluate('window.companion.deleteDeepSeekKey()');
  assert.equal((await evaluate('window.companion.state()')).hasDeepSeekKey,false);
  await evaluate('window.companion.saveSettings('+JSON.stringify({...settings,deepseekKey:'',chatProvider:'local'})+')');
  fs.writeFileSync(path.join(directory,'deepseek-provider-settings-result.json'),JSON.stringify({status:'passed',version:initial.version,checks:['provider UI','dedicated encrypted key','no key in public state','provider switch and persistence','conversation cleared on switch','active-task settings refusal','unsupported model refusal','key removal'],remoteInference:false},null,2));
};
